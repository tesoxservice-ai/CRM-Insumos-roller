create table if not exists configuracion (
  id serial primary key,
  clave text unique not null,
  valor numeric not null,
  descripcion text
);

create table if not exists precios_textiles (
  id serial primary key,
  material text unique not null,
  precio numeric not null,
  descripcion text
);

create table if not exists precios_verticales (
  id serial primary key,
  material text unique not null,
  precio numeric not null,
  descripcion text
);

create table if not exists precios_roller (
  id serial primary key,
  ancho_cm integer not null,
  alto_cm integer not null,
  precio numeric not null,
  unique (ancho_cm, alto_cm)
);

